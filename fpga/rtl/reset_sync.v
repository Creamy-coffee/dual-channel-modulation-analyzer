// ============================================================================
// 模块名称：reset_sync
// 功能概述：异步复位同步释放（Asynchronous Reset Synchronous Release）
//
// 【为什么需要异步复位同步释放】
//   在 FPGA/ASIC 设计中，复位信号的设计至关重要，主要有以下几种复位方式：
//
//   1. 纯异步复位：复位信号直接接在触发器的异步复位端，复位立即生效。
//      - 优点：复位响应快，不依赖时钟，功耗低
//      - 缺点：复位释放时（撤防）如果不满足 recovery/removal 时间要求，
//              触发器可能进入亚稳态（metastability），导致系统不稳定
//
//   2. 纯同步复位：复位信号只在时钟沿采样，复位和释放都与时钟同步。
//      - 优点：释放时天然满足时序要求，不会有亚稳态问题
//      - 缺点：复位需要时钟才能生效，某些低功耗/无时钟场景无法使用；
//              综合时可能把复位综合成数据路径，占用更多逻辑资源
//
//   3. 异步复位同步释放（本模块采用）：结合两者优点。
//      - 复位触发（assert）是异步的：复位信号一拉低，立即生效，不依赖时钟
//      - 复位释放（de-assert）是同步的：复位信号拉高后，经过两级触发器同步
//        后才释放，确保释放沿满足 recovery/removal 时间要求
//
//   【recovery time（恢复时间）】：异步复位信号释放沿到下一个时钟有效沿
//        之间所需的最小时间，类似建立时间（setup time）
//   【removal time（移除时间）】：异步复位信号释放沿相对于时钟有效沿
//        之后必须保持的最小时间，类似保持时间（hold time）
//   若不满足这两个时间要求，触发器输出可能在一段时间内处于不确定状态
//   （亚稳态），传播到后续逻辑会导致系统功能错误。
//
// 【工作原理】
//   使用两级（本实现为四级以增强 MTBF）触发器链：
//   - 所有触发器的异步复位端都接 arst_n（异步复位信号，低有效）
//   - 第一级触发器 D 端接 1'b1（VCC）
//   - 后续每一级 D 端接前一级的 Q 输出
//   - 最后一级 Q 输出即为同步后的复位信号 rst_n
//
//   复位触发过程（异步）：
//     arst_n 拉低 → 所有触发器立即清零 → rst_n = 0（复位有效）
//     此过程不依赖时钟，立即生效
//
//   复位释放过程（同步）：
//     arst_n 拉高 → 在第一个时钟上升沿，第一级触发器输出变1
//                    第二个时钟上升沿，第二级触发器输出变1
//                    ...
//                    第N个时钟上升沿，最后一级输出变1（复位释放）
//     由于最后一级触发器的输出是由时钟沿驱动更新的，
//     所以下游所有触发器看到的复位释放沿都与时钟严格同步，
//     天然满足 recovery/removal 时间要求，消除亚稳态风险。
//
// 【时序图说明】
//
//   时钟 clk:        ____----____----____----____----____----____----
//   异步复位 arst_n: ----------______________________________________
//                                     ^ 复位触发（异步，立即生效）
//
//   sync_ff[0]:      11111100000000000000011111111111111111111111111
//                           ^ 立即清零          ^ 第1个clk后变1
//   sync_ff[1]:      11111100000000000000000000011111111111111111111
//                           ^ 立即清零              ^ 第2个clk后变1
//   sync_ff[2]:      11111100000000000000000000000000011111111111111
//                           ^ 立即清零                  ^ 第3个clk后变1
//   sync_ff[3]:      11111100000000000000000000000000000000011111111
//                           ^ 立即清零                      ^ 第4个clk后变1
//   输出 rst_n:      --------------------------------------------------
//                                            复位释放（同步于时钟）
//
//   注：复位触发时所有触发器立即清零（异步），复位释放时逐级传递（同步）。
//       本实现使用4级触发器而非常见的2级，目的是进一步提高 MTBF
//       （平均无故障时间），在高频率设计中更可靠。
//
// 【与纯同步复位、纯异步复位的对比总结】
//   +------------------+--------------+--------------+--------------------+
//   | 特性             | 纯异步复位   | 纯同步复位   | 异步复位同步释放   |
//   +------------------+--------------+--------------+--------------------+
//   | 复位触发是否依赖时钟 | 否          | 是           | 否                 |
//   | 复位释放是否依赖时钟 | 否          | 是           | 是                 |
//   | 亚稳态风险       | 有（释放时） | 无           | 无                 |
//   | 资源占用         | 少           | 多           | 中                 |
//   | 适用场景         | 低功耗设计等 | 对复位可靠性 | 大多数现代FPGA设计 |
//   |                  |              | 要求高的场景 |                    |
//   +------------------+--------------+--------------+--------------------+
//
// ============================================================================

`timescale 1ns/1ps    // 时间单位：1ns，时间精度：1ps
`default_nettype none // 关闭隐式线网声明，所有信号必须显式声明（防止拼写错误）

module reset_sync(
    input  wire clk,     // 系统时钟输入，复位同步操作的参考时钟
    input  wire arst_n,  // 异步复位输入，低电平有效。直接来自外部复位引脚或PLL锁定信号等
    output wire rst_n    // 同步后的复位输出，低电平有效。供下游所有同步逻辑使用
);

    // ------------------------------------------------------------------
    // 内部信号：sync_ff（四级同步触发器链）
    //
    // 位宽：4位，即四级触发器级联
    //   sync_ff[0] = 第一级，接收 1'b1（VCC）
    //   sync_ff[1] = 第二级，打第二拍
    //   sync_ff[2] = 第三级，打第三拍
    //   sync_ff[3] = 第四级，打第四拍，作为最终输出
    //
    // 为什么用4级而不是2级？
    //   - 标准的亚稳态防护通常是2级触发器
    //   - 本设计用4级是为了在高频设计中提供更高的 MTBF
    //     （Mean Time Between Failures，平均无故障时间）
    //   - 增加级数可以指数级降低亚稳态传播到输出的概率
    //
    // 【ASYNC_REG 属性说明】
    //   (* ASYNC_REG="TRUE" *) 是 Xilinx 综合属性，告诉综合工具：
    //   1. 这些触发器的 D 输入端是异步信号（跨时钟域或异步复位相关）
    //   2. 综合/布局布线时应将这些触发器尽可能靠近摆放
    //      （放在同一个 slice 或相邻的 slice 中）
    //   3. 减少走线延迟，最大化留给亚稳态的分辨时间
    //   4. 防止综合工具做不必要的优化（如复制、移位等）
    //   这是 FPGA 设计中同步器的标准做法。
    // ------------------------------------------------------------------
    (* ASYNC_REG="TRUE" *) reg [3:0] sync_ff; // 四级同步复位触发器链

    // ------------------------------------------------------------------
    // 主时序逻辑：四级移位寄存器
    //
    // 敏感列表：posedge clk 或 negedge arst_n
    //   - 时钟上升沿触发正常的移位操作
    //   - arst_n 下降沿（复位触发）触发异步清零
    //
    // 复位触发时（arst_n = 0）：
    //   sync_ff <= 4'b0000（全部清零，复位有效）
    //   这是异步的，不依赖时钟，立即生效
    //
    // 正常移位时（arst_n = 1，clk 上升沿）：
    //   sync_ff <= {sync_ff[2:0], 1'b1}
    //   即左移一位，最低位补1（VCC）
    //   等价于：
    //     sync_ff[0] <= 1'b1
    //     sync_ff[1] <= sync_ff[0]
    //     sync_ff[2] <= sync_ff[1]
    //     sync_ff[3] <= sync_ff[2]
    //
    // 复位释放过程：
    //   arst_n 拉高后，经过 4 个时钟周期，sync_ff[3] 才会变 1
    //   这样 rst_n 的释放沿与时钟严格同步，满足下游触发器的 recovery 要求
    // ------------------------------------------------------------------
    always @(posedge clk or negedge arst_n)
        if(!arst_n)                 // 异步复位：arst_n 为低时，所有触发器立即清零
            sync_ff <= 0;           //   4位全部置0，rst_n输出为0（复位有效）
        else                        // 时钟上升沿：移位操作
            sync_ff <= {sync_ff[2:0], 1'b1}; // 左移一位，LSB补1
                                            // 即高3位 = 原来的低3位，最低位 = 1

    // ------------------------------------------------------------------
    // 输出赋值：取四级触发器链的最后一级作为同步复位输出
    //
    // 选择 sync_ff[3]（第4级）而不是 sync_ff[1]（第2级）的原因：
    //   - 提供更高的亚稳态防护等级
    //   - 复位释放延迟为 4 个时钟周期，这在系统启动时完全可以接受
    //   - 对于复位信号来说，多几个周期的延迟不影响功能
    // ------------------------------------------------------------------
    assign rst_n = sync_ff[3];  // 同步复位输出，低有效

endmodule

`default_nettype wire  // 恢复默认的隐式线网声明，不影响其他模块
