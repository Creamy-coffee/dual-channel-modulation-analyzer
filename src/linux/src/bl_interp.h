/*
 * bl_interp.h —— 带限（sinc 多相 FIR）重采样
 *
 * 用途：把「采样点」还原成「连续波形」再按屏幕像素重新取样。
 * 带限插值适用于满足采样定理、未混叠且具有足够记录支撑的信号。
 * 65 MSPS 对 30 MHz 仅有约 2.17 点/周期；有限抽头和边界处理均有误差。
 * 合成信号上的算法误差不代表 ADC、模拟前端和整机的测量精度。
 *
 * 它**不**做这些事（写清楚免得被当成万灵药）：
 *   · 不增加采样率、不提高模拟带宽、不提高 ADC 有效位数
 *   · 不降噪 —— 通带一直开到原奈奎斯特，带内噪声原样保留
 *   · 不能救真混叠：超过 32.5 MHz 的成分早就折叠进来了，插值只会把它画得更平滑
 */
#include <stdbool.h>

#ifndef BL_INTERP_H
#define BL_INTERP_H

/*
 * 在 [0, n) 这段输入上，按浮点坐标 t0 + i*dt 取 nout 个重建值。
 *   t0 = 0 表示第 0 个输入样点所在的位置
 *   dt < 1 放大（输出点比输入密），dt > 1 收缩
 * 滤波器支撑不够的边界区域（前后各 BL_DELAY 个输入样点）自动退回线性插值，
 * 否则会出现幅度塌陷。
 * 超出实际记录范围或无效的坐标输出 NAN，显示端应留空，不跨缺口连线。
 */
/*
 * limit_overshoot：把重建值**钳位在原始采样点的局部极值范围内**。
 *
 * 有限带宽和重建滤波可能产生振铃；不能仅凭外观判断其是否来自真实输入。
 * 钳位属于非线性显示处理，可能压低真实峰值，尤其是接近奈奎斯特的正弦。
 * 不应用钳位后的显示样点进行精度标定或作为原始采样导出。
 */
int bl_support_radius(void);

void bl_resample(const float *x, int n, float *y, int nout, float t0, float dt,
                 bool limit_overshoot);

#endif /* BL_INTERP_H */
